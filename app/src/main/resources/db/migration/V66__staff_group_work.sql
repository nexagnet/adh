CREATE TABLE staff_member (
    username text PRIMARY KEY,
    display_name text NOT NULL,
    password_hash text NOT NULL,
    active boolean NOT NULL DEFAULT true
);

CREATE TABLE staff_group (
    username text NOT NULL REFERENCES staff_member(username) ON DELETE CASCADE,
    group_id bigint NOT NULL REFERENCES zalo_group(id) ON DELETE CASCADE,
    PRIMARY KEY (username, group_id)
);

ALTER TABLE handoff ADD COLUMN assigned_to text REFERENCES staff_member(username);
CREATE TABLE handoff_assignment_event (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    handoff_id bigint NOT NULL REFERENCES handoff(id) ON DELETE CASCADE,
    actor text NOT NULL,
    assignee text NOT NULL,
    action text NOT NULL CHECK (action IN ('CLAIM', 'ASSIGN', 'RESOLVE')),
    created_at timestamptz NOT NULL DEFAULT now()
);
