CREATE TABLE shop_order_draft (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    handoff_id bigint NOT NULL REFERENCES handoff(id) ON DELETE CASCADE,
    token uuid NOT NULL UNIQUE,
    product_id text NOT NULL,
    sku_id text NOT NULL,
    seller_sku text NOT NULL,
    product_name text NOT NULL,
    quantity integer NOT NULL CHECK (quantity BETWEEN 1 AND 100),
    observed_unit_price numeric(16, 4) NOT NULL CHECK (observed_unit_price >= 0),
    currency varchar(3) NOT NULL,
    observed_stock bigint NOT NULL CHECK (observed_stock >= 0),
    created_by text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);
